#!/usr/bin/env python3
"""Read alpha geometry only; never change the approved source PNGs."""
import json
from pathlib import Path
from PIL import Image
ROOT=Path(__file__).resolve().parents[1]

def frames(name, xs, ys, used_rows=None):
    im=Image.open(ROOT/'assets/pixel/summer'/f'{name}.png').convert('RGBA')
    alpha=im.getchannel('A')
    rows=[]
    for r in range(used_rows or len(ys)-1):
        row=[]
        for c in range(len(xs)-1):
            cell=(round(xs[c]),round(ys[r]),round(xs[c+1]),round(ys[r+1]))
            # Alpha threshold ignores transparent generation gutters, not sprite pixels.
            bounds=alpha.crop(cell).point(lambda a:255 if a>=192 else 0).getbbox()
            assert bounds, (name,r,c)
            x,y=cell[0]+bounds[0],cell[1]+bounds[1]
            w,h=bounds[2]-bounds[0],bounds[3]-bounds[1]
            row.append([x,y,w,h,w/2,h])
        rows.append(row)
    return rows

def resident_frames(name, used_rows):
    im=Image.open(ROOT/'assets/pixel/summer'/f'{name}.png').convert('RGBA')
    width,height=im.size
    alpha=im.getchannel('A')
    values=list(alpha.tobytes())
    seen=bytearray(width*height)
    silhouettes=[]
    for start,opacity in enumerate(values):
        if opacity<192 or seen[start]:continue
        seen[start]=1
        stack=[start]
        points=[]
        while stack:
            point=stack.pop()
            points.append(point)
            x,y=point%width,point//width
            for other in ([point-1] if x>0 else [])+([point+1] if x<width-1 else [])+([point-width] if y>0 else [])+([point+width] if y<height-1 else []):
                if not seen[other] and values[other]>=192:
                    seen[other]=1
                    stack.append(other)
        if len(points)>3000:
            xs=[v%width for v in points];ys=[v//width for v in points]
            silhouettes.append((min(xs),min(ys),max(xs)+1,max(ys)+1,points))
    expected=32 if name=='edric' else 16
    assert len(silhouettes)==expected,(name,len(silhouettes))
    silhouettes.sort(key=lambda item:item[1])
    rows=[]
    for r in range(used_rows):
        row=[]
        for left,top,right,bottom,points in sorted(silhouettes[r*4:r*4+4],key=lambda item:item[0]):
            # Register the body below the head; a large swinging tail/cape must not move the pivot.
            head=sorted(v%width for v in points if top+(bottom-top)*.15<=v//width<top+(bottom-top)*.28)
            pivot=head[len(head)//2]
            x,y=max(0,left-2),max(0,top-2)
            w,h=min(width,right+2)-x,min(height,bottom+2)-y
            row.append([x,y,w,h,pivot-x,bottom-y])
        rows.append(row)
    return rows

def edges(total,n):return [i*total/n for i in range(n+1)]
all_frames={
 'CROPS':frames('crops',[0,320,625,920,1235,1536],[0,370,695,1024]),
 'FACILITIES':frames('facilities',edges(2172,3),[0,724]),
 'EDRIC':resident_frames('edric',4),
 'SUYUE':resident_frames('suyue',4),
}
# A fixed scale per atlas, with per-pose baseline registration, prevents pulsing.
text='extends RefCounted\n# Generated by tools/register_summer_art.py; original PNGs preserved.\n'
for name,rows in all_frames.items():
 text+='const '+name+' := '+json.dumps(rows,separators=(',',':'))+'\n'
(ROOT/'scripts/summer_frames.gd').write_text(text)
print({name:sum(map(len,rows)) for name,rows in all_frames.items()})
