#!/usr/bin/env python3
"""Read alpha bounds for production autumn sprites without modifying PNGs."""
from pathlib import Path
import json
from PIL import Image
ROOT=Path(__file__).resolve().parents[1]
def frames(name,xs,ys):
    image=Image.open(ROOT/'assets/pixel/autumn'/f'{name}.png').convert('RGBA')
    assert image.size==(1536,1024)
    alpha=image.getchannel('A')
    rows=[]
    for top,bottom in zip(ys,ys[1:]):
        row=[]
        for left,right in zip(xs,xs[1:]):
            b=alpha.crop((left,top,right,bottom)).point(lambda a:255 if a>=192 else 0).getbbox()
            assert b,(name,left,top)
            row.append([left+b[0],top+b[1],b[2]-b[0],b[3]-b[1]])
        rows.append(row)
    return rows
if __name__=='__main__':
    data={'CROPS':frames('crops',[0,300,610,925,1280,1536],[0,350,660,1024]),
          'OBJECTS':frames('objects',[0,384,784,1174,1536],[0,512,1024])}
    (ROOT/'scripts/autumn_frames.gd').write_text('extends RefCounted\n# Generated by tools/register_autumn_art.py; PNG originals preserved.\n'+''.join('const '+k+' := '+json.dumps(v,separators=(',',':'))+'\n' for k,v in data.items()))
    print({k:sum(map(len,v)) for k,v in data.items()})
